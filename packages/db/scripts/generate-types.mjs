import { mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { spawnSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const packageRoot = path.resolve(scriptDir, '..')
const repoRoot = path.resolve(packageRoot, '../..')
const outputDir = path.join(packageRoot, 'src', 'generated')
const outputFilePath = path.join(outputDir, 'database.types.ts')
const cliVersion = '2.88.0'
const schemaList = ['catalog', 'legality', 'user_data', 'social', 'gameplay']

const databaseUrl =
  process.env.DATABASE_URL ?? process.env.SUPABASE_DB_URL ?? null

function quoteArg(arg) {
  return /[\s"]/u.test(arg) ? `"${arg.replaceAll('"', '\\"')}"` : arg
}

function runCorepack(corepackArgs) {
  return process.platform === 'win32'
    ? spawnSync(
        process.env.ComSpec ?? 'cmd.exe',
        [
          '/d',
          '/s',
          '/c',
          ['corepack', ...corepackArgs].map(quoteArg).join(' '),
        ],
        {
          cwd: repoRoot,
          encoding: 'utf8',
          env: process.env,
          maxBuffer: 20 * 1024 * 1024,
        },
      )
    : spawnSync('corepack', corepackArgs, {
        cwd: repoRoot,
        encoding: 'utf8',
        env: process.env,
        maxBuffer: 20 * 1024 * 1024,
      })
}

function assertCommandSucceeded(result, fallbackMessage) {
  if (result.error) {
    console.error(result.error)
    process.exit(1)
  }

  if (result.status !== 0) {
    process.stderr.write(result.stderr || fallbackMessage)
    process.exit(result.status ?? 1)
  }
}

const generateArgs = [
  'pnpm',
  'dlx',
  `supabase@${cliVersion}`,
  'gen',
  'types',
  'typescript',
]

if (databaseUrl) {
  generateArgs.push('--db-url', databaseUrl)
} else {
  generateArgs.push('--local')
}

for (const schema of schemaList) {
  generateArgs.push('--schema', schema)
}

const generateResult = runCorepack(generateArgs)

assertCommandSucceeded(generateResult, 'Failed to generate database types.\n')

const header = `/* eslint-disable */
/**
 * DO NOT EDIT MANUALLY.
 *
 * Generated by:
 *   corepack pnpm db:types:generate
 *
 * Source:
 *   - official Supabase CLI
 *   - local database via --local, or DATABASE_URL / SUPABASE_DB_URL via --db-url
 */

`

await mkdir(outputDir, { recursive: true })
await writeFile(outputFilePath, header + generateResult.stdout, 'utf8')

const formatResult = runCorepack([
  'pnpm',
  'exec',
  'prettier',
  '--write',
  outputFilePath,
])

assertCommandSucceeded(
  formatResult,
  'Failed to format generated database types.\n',
)

process.stdout.write(`Generated ${path.relative(repoRoot, outputFilePath)}\n`)
